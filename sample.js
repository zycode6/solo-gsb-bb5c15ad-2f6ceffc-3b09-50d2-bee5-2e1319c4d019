var RULES = [
  {
    id: 'sample-a',
    code: '甲',
    aliases: ['王海涛', '王总', '老王'],
    selections: [],
  },
  {
    id: 'sample-b',
    code: '乙',
    aliases: ['李梦琪', '梦琪', '李总'],
    selections: [],
  },
  {
    id: 'sample-c',
    code: '丙',
    aliases: ['陈守义', '老陈', '老前辈'],
    selections: [
      // 显式框选演示：“隔壁公司的老王”这一整段被框给「丙」，
      // 其中虽包含称呼“老王”（属于甲），仍以显式框选为准。
      { start: 0, end: 0 }, // 占位，载入后按文本计算
    ],
  },
];

// 示例文本确定后再计算显式区间，避免手工数字符
(function resolveSelections() {
  var phrase = '隔壁公司的老王';
  var idx = TEXT.indexOf(phrase);
  var c = RULES[2];
  c.selections = idx === -1 ? [] : [{ start: idx, end: idx + phrase.length }];
})();

